def render() -> str:
    lines = [
        "// font_rom: 5x7 glyphs in 8x8 cells (row 0 = top, bit 7 = left column).",
        "// GENERATED by sw/board/gen_font.py -- do not edit by hand.",
        "",
        "`default_nettype none",
        "",
        "module font_rom (",
        "    input  wire logic [7:0] ch,     // ASCII; unknown characters are blank",
        "    input  wire logic [2:0] row,",
        "    output      logic [7:0] bits",
        ");",
        "    logic [63:0] g;",
        "    always_comb begin",
        "        unique case (ch)",
    ]
    for c, rows in GLYPHS.items():
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), c
        v = 0
        for r in rows + ["....."]:
            v = (v << 8) | int(r.replace("#", "1").replace(".", "0") + "000", 2) >> 1
        lines.append(f"            8'h{ord(c):02x}: g = 64'h{v:016x};   // '{c}'")
    lines += [
        "            default: g = '0;",
        "        endcase",
        "        bits = g[8 * (7 - row) +: 8];",
        "    end",
        "endmodule",
        "",
        "`default_nettype wire",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    out = Path(__file__).resolve().parents[2] / "rtl" / "board" / "font_rom.sv"
    out.write_text(render())
    print(f"wrote {out}")
