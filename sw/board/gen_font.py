def render() -> str:
    lines = [
        "`default_nettype none",
        "",
        "module font_rom (",
        "    input  wire logic       clk,",
        "    input  wire logic [6:0] ch,",
        "    input  wire logic [2:0] row,",
        "    output      logic [7:0] bits",
        ");",
        "    always_ff @(posedge clk) begin",
        "        unique case ({ch, row})",
    ]
    for c, rows in GLYPHS.items():
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), c
        for i, r in enumerate(rows):
            v = int(r.replace("#", "1").replace(".", "0") + "000", 2) >> 1
            if v:
                lines.append(f"            {{7'h{ord(c):02x}, 3'd{i}}}: bits <= 8'h{v:02x};")
    lines += [
        "            default: bits <= '0;",
        "        endcase",
        "    end",
        "endmodule",
        "",
        "`default_nettype wire",
        "",
    ]
    return "\n".join(lines)

if __name__ == "__main__":
    out = Path(__file__).resolve().parents[2] / "rtl" / "board" / "font_rom.sv"
    out.write_text(render())
